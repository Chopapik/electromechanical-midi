"""Generate the checked-in browser catalog from the backend's pure preset data.

Run after editing host/arrangement_presets.py; --check never writes files.
The generated file ships with web/, so the Node-only Docker build needs no Python.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'host'))
from arrangement_presets import PRESETS

TARGET = ROOT / 'web/src/generated/arrangementPresets.ts'


def render():
    records = [{'id':p.id, 'label':p.label, 'descriptions':p.descriptions}
               for p in sorted(PRESETS, key=lambda p:p.ui_order)]
    return ('// Generated by scripts/generate_preset_catalog.py; edit host/arrangement_presets.py.\n'
            'export const arrangementPresets = '+json.dumps(records, ensure_ascii=False, indent=2)
            +' as const\n'
            "export type ArrangementPreset = typeof arrangementPresets[number]['id']\n"
            'export function isArrangementPreset(value:unknown):value is ArrangementPreset {\n'
            "  return typeof value==='string' && arrangementPresets.some(preset=>preset.id===value)\n"
            '}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            parser.exit(1, 'Preset catalog is stale; run scripts/generate_preset_catalog.py\n')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(result)


if __name__ == '__main__':
    main()
